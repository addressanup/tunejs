// Bundles the compiled DSP kernel + worklet processor into a single source string embedded in
// src/adapters/dsp-worklet-source.ts. Run after `tsc -p tsconfig.json`. `--check` verifies the
// committed file is in sync with dist/ (used by `npm run build` and CI).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const target = join(root, 'src/adapters/dsp-worklet-source.ts');

function strip(path) {
  const lines = readFileSync(path, 'utf8').split('\n').filter(line => !line.startsWith('//# sourceMappingURL'));
  const kept = [];
  for (let line of lines) {
    if (/^import\s.*from\s+['"].*['"];?\s*$/.test(line)) continue;
    line = line.replace(/^export /, '');
    if (line.trim() === 'export {};' || line.trim() === 'export {};') continue;
    kept.push(line);
  }
  const text = kept.join('\n');
  if (/^\s*import\s/m.test(text)) throw new Error(`${path}: unbundled import remains — the worklet source must be self-contained.`);
  return text;
}

const source = `(function () {\n${strip(join(root, 'dist/dsp.js'))}\n${strip(join(root, 'dist/worklet/processor.js'))}\n})();\n`;
const generated = `// generated by scripts/bundle-worklet.mjs — do not edit
export const DSP_PROCESSOR_NAME = 'tunejs-dsp';
export const DSP_PROCESSOR_SOURCE = ${JSON.stringify(source)};
`;

if (process.argv.includes('--check')) {
  let committed = '';
  try { committed = readFileSync(target, 'utf8'); } catch { /* missing */ }
  if (committed !== generated) {
    console.error('src/adapters/dsp-worklet-source.ts is stale — run npm run prepare:worklet.');
    process.exit(1);
  }
  console.log('WORKLET_SOURCE_FRESH');
} else {
  writeFileSync(target, generated);
  console.log(`wrote ${target} (${source.length} bytes)`);
}
