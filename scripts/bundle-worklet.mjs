// Bundles the compiled DSP kernel into host-consumable sources:
//  - src/adapters/dsp-worklet-source.ts: dsp.js + the browser processor as a Blob-loaded IIFE.
//  - src/worklet/native-kernel.ts: dsp.js inlined inside one 'worklet' factory for
//    react-native-worklets serialization (the native DSP path runs the same kernel).
// Run after `tsc -p tsconfig.json`. `--check` verifies committed files are in sync with dist/.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const browserTarget = join(root, 'src/adapters/dsp-worklet-source.ts');
const nativeTarget = join(root, 'src/worklet/native-kernel.ts');

function strip(path) {
  const lines = readFileSync(path, 'utf8').split('\n').filter(line => !line.startsWith('//# sourceMappingURL'));
  const kept = [];
  for (let line of lines) {
    if (/^import\s.*from\s+['"].*['"];?\s*$/.test(line)) continue;
    line = line.replace(/^export /, '');
    if (line.trim() === 'export {};') continue;
    kept.push(line);
  }
  const text = kept.join('\n');
  if (/^\s*import\s/m.test(text)) throw new Error(`${path}: unbundled import remains — the worklet source must be self-contained.`);
  return text;
}

const dsp = strip(join(root, 'dist/dsp.js'));
const browserSource = `(function () {\n${dsp}\n${strip(join(root, 'dist/worklet/processor.js'))}\n})();\n`;
const browserGenerated = `// generated by scripts/bundle-worklet.mjs — do not edit
export const DSP_PROCESSOR_NAME = 'tunejs-dsp';
export const BINAURAL_PROCESSOR_NAME = 'tunejs-binaural';
export const DSP_PROCESSOR_SOURCE = ${JSON.stringify(browserSource)};
`;

// Native kernel: every name exported by dist/dsp.js, returned from the worklet factory.
const rawDsp = readFileSync(join(root, 'dist/dsp.js'), 'utf8');
const names = [...rawDsp.matchAll(/^export (?:class|function|const|let) (\w+)/gm)].map(m => m[1]);
const kernelSource = rawDsp
  .split('\n').filter(line => !line.startsWith('//# sourceMappingURL'))
  .map(line => line.replace(/^export /, ''))
  .filter(line => !/^import\s.*from\s+['"].*['"];?\s*$/.test(line) && line.trim() !== 'export {};')
  .join('\n');
const nativeGenerated = `// @ts-nocheck
// generated by scripts/bundle-worklet.mjs — do not edit
export function tunejsNativeKernel(): any { 'worklet';
${kernelSource}
return { ${names.join(', ')} };
}
`;

const outputs = [[browserTarget, browserGenerated], [nativeTarget, nativeGenerated]];
if (process.argv.includes('--check')) {
  let stale = false;
  for (const [target, generated] of outputs) {
    let committed = '';
    try { committed = readFileSync(target, 'utf8'); } catch { /* missing */ }
    if (committed !== generated) { console.error(`${target} is stale — run npm run prepare:worklet.`); stale = true; }
  }
  if (stale) process.exit(1);
  console.log('WORKLET_SOURCES_FRESH');
} else {
  for (const [target, generated] of outputs) writeFileSync(target, generated);
  console.log(`wrote ${browserTarget} (${browserSource.length} bytes), ${nativeTarget}`);
}
